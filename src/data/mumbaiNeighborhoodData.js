/**
 * Deterministic hash generator for arbitrary map points clicked anywhere in Mumbai
 */
export function getArbitraryLocationMetrics(lat, lng, address = "") {
  const str = `${lat.toFixed(4)},${lng.toFixed(4)}`;
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const posHash = Math.abs(hash);

  const price = Number((0.9 + (posHash % 45) / 10).toFixed(2));
  const school = 65 + (posHash % 30);
  const hospital = 68 + ((posHash + 5) % 28);
  const market = 70 + ((posHash + 11) % 26);
  const crimeRisk = 72 + ((posHash + 17) % 24); // Higher = safer
  const connectivity = 70 + ((posHash + 3) % 27);
  const airQuality = 60 + ((posHash + 9) % 32);
  const floodSafety = 65 + ((posHash + 13) % 28);
  const futureDev = 75 + ((posHash + 21) % 22);

  return {
    id: `custom-${posHash}`,
    name: address || `Custom Point (${lat.toFixed(4)}, ${lng.toFixed(4)})`,
    city: "Mumbai",
    latitude: Number(lat.toFixed(4)),
    longitude: Number(lng.toFixed(4)),
    averagePriceCr: price,
    schoolScore: school,
    hospitalScore: hospital,
    marketScore: market,
    connectivityScore: connectivity,
    crimeRiskScore: crimeRisk,
    airQualityScore: airQuality,
    floodSafetyScore: floodSafety,
    noiseScore: 65,
    infrastructureScore: futureDev,
    nearestSchoolKm: Number((0.5 + (posHash % 15) / 10).toFixed(1)),
    nearestHospitalKm: Number((0.7 + ((posHash + 2) % 20) / 10).toFixed(1)),
    nearestMarketKm: Number((0.3 + ((posHash + 4) % 10) / 10).toFixed(1)),
    railwayAccessScore: connectivity,
    metroAccessScore: connectivity,
    roadConnectivityScore: connectivity,
    futureDevelopmentScore: futureDev,
    summary: `Selected coordinate point in Mumbai Metropolitan Region. Synthetic metrics generated for prototype evaluation.`
  };
}
